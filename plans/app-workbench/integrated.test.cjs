const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
test('既有对话新增右侧工作台：三会话共享草稿，Tag 固定全项目版本',async()=>{
 const {Window}=await import(require.resolve('happy-dom',{paths:[path.resolve('apps/web')]}));
 const w=new Window();const d=w.document;
 d.write(fs.readFileSync('plans/app-workbench/integrated.html','utf8'));
 w.eval(fs.readFileSync('plans/app-workbench/layouts.js','utf8'));
 assert.equal(d.querySelector('.preview-footer'),null);
 assert.equal(d.querySelectorAll('.sidebar [data-action="open"]').length,1);
 assert.ok(d.querySelector('.project [data-action="open"]'));
 assert.equal(d.querySelector('.existing-chat-header [data-action="open"]'),null);
 assert.equal(d.querySelector('#workbench-frame').tagName,'IFRAME');
 const click=a=>d.querySelector(`[data-action="${a}"]`).click();
 click('send');
 assert.match(d.querySelector('#workbench-frame').srcdoc,/全部状态/);
 d.querySelector('#message').value='保留 A 对话输入';
 click('session-other');click('send');
 assert.match(d.querySelector('#workbench-frame').srcdoc,/全部状态/);
 assert.match(d.querySelector('#workbench-frame').srcdoc,/导出客户/);
 click('session-third');click('send');
 assert.match(d.querySelector('#workbench-frame').srcdoc,/负责人/);
 click('create');click('confirm-create');
 click('session-main');assert.equal(d.querySelector('#message').value,'保留 A 对话输入');
 click('deploy');click('confirm-deploy');
 assert.match(d.querySelector('#production').textContent,/v1.3.0/);
 const select=d.querySelector('#version');select.value='v1.3.0';select.dispatchEvent(new w.Event('change'));
 click('start');click('session-third');assert.equal(d.querySelector('#version').value,'v1.3.0');
 assert.match(d.querySelector('#workbench-frame').srcdoc,/负责人/);
 click('toggle-workbench');assert.ok(d.body.classList.contains('workbench-closed'));
 click('open');assert.ok(!d.body.classList.contains('workbench-closed'));
 click('share');assert.match(d.querySelector('#action-panel').textContent,/网关认证/);
 click('close');click('setup');
 d.querySelector('#workbench-dir').value='apps/customer';click('save-workbench');
 click('setup');assert.equal(d.querySelector('#workbench-dir').value,'apps/customer');click('close');
 click('rollback');click('confirm-rollback');
 assert.match(d.querySelector('#production').textContent,/v1.2.0/);
 w.happyDOM.abort();
});
