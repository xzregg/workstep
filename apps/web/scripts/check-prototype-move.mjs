import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'../../desktop/node_modules/playwright-core/index.mjs')
const browser=await chromium.launch({executablePath:process.env.CHROME_BINARY||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true})
try{
  const page=await browser.newPage({viewport:{width:1200,height:800}})
  await fs.mkdir('../../tmp/prototype-move',{recursive:true})
  const bridge=(await fs.readFile('../daemon/data/prototype-editor.js','utf8')).replace('__WS_VERSION__',JSON.stringify('move-version'))
  const html='<!doctype html><style>body{margin:0}#stage{position:relative;margin:40px;width:720px;height:400px;padding:20px;border:1px solid #aaa}#target{position:absolute;left:80px;top:80px;width:100px;height:50px}#neighbor{position:absolute;left:300px;top:180px;width:120px;height:80px;background:#ddd}</style><div id="stage"><button id="target" data-ws-node="n1">Move me</button><div id="neighbor" data-ws-node="n2">Align here</div></div>'
  await page.setContent('<iframe sandbox="allow-scripts" style="width:950px;height:650px"></iframe>')
  await page.evaluate(source=>{window.messages=[];window.addEventListener('message',event=>{if(event.data?.source==='workstep-prototype')window.messages.push(event.data)});document.querySelector('iframe').srcdoc=source},html+'<script>'+bridge+'</script>')
  await page.waitForFunction(()=>window.messages.some(message=>message.type==='ready'))
  const host=data=>page.evaluate(message=>document.querySelector('iframe').contentWindow.postMessage({source:'workstep-prototype-host',version:'move-version',...message},'*'),data)
  await host({type:'mode',enabled:true})
  const frame=page.frameLocator('iframe'),target=frame.locator('#target'),neighbor=frame.locator('#neighbor')
  await target.click()
  assert.equal(await page.evaluate(()=>window.messages.filter(m=>m.type==='select').at(-1).selection.selector),'#target','selected element has a usable CSS selector')
  const initial=await target.boundingBox(),other=await neighbor.boundingBox()
  const bodyStart={x:initial.x+initial.width/2,y:initial.y+initial.height/2}
  await page.mouse.move(bodyStart.x,bodyStart.y);await page.mouse.down()
  await page.mouse.move(bodyStart.x+40,bodyStart.y+30,{steps:6});await page.mouse.up()
  assert.deepEqual(await target.boundingBox(),initial,'dragging element body only selects; it does not move')
  assert.equal(await page.evaluate(()=>window.messages.filter(message=>message.type==='edit').length),0)
  await target.click()
  const start={x:initial.x+initial.width-12,y:initial.y-16}
  await page.mouse.move(start.x,start.y);await page.mouse.down()
  await page.mouse.move(start.x+other.x+other.width-initial.x+2,start.y+other.y-initial.y+2,{steps:12})
  const aligned=await target.boundingBox()
  assert.ok(Math.abs(aligned.x-(other.x+other.width))<1,'snaps to sibling right edge')
  assert.ok(Math.abs(aligned.y-other.y)<1,'snaps to sibling top edge')
  assert.equal(await page.evaluate(()=>window.messages.filter(message=>message.type==='edit').length),0,'dragging does not write')
  await page.screenshot({path:'../../tmp/prototype-move/sibling-alignment.png'})
  await page.mouse.up()
  await page.waitForFunction(()=>window.messages.some(message=>message.type==='edit'&&message.values.translate))
  const moved=await page.evaluate(()=>window.messages.filter(message=>message.type==='edit'))
  assert.equal(moved.length,1)
  assert.equal(moved[0].node_id,'n1')
  assert.equal(moved[0].values.translate,'340px 100px')
  assert.deepEqual(await neighbor.boundingBox(),other,'sibling stays unchanged')
  await host({type:'preview-reset',node_id:'n1'})
  await page.waitForFunction(()=>window.messages.some(message=>message.type==='drag-state'&&!message.active))
  const restored=await target.boundingBox()
  await page.mouse.move(restored.x+restored.width-12,restored.y-16);await page.mouse.down()
  await page.mouse.move(restored.x+restored.width+58,restored.y+59,{steps:6})
  await page.keyboard.press('Escape');await page.mouse.up()
  assert.deepEqual(await target.boundingBox(),initial,'Escape cancels and restores position')
  assert.equal(await page.evaluate(()=>window.messages.filter(message=>message.type==='edit').length),1,'cancel does not write')
  assert.equal(await page.evaluate(()=>window.messages.filter(message=>message.type==='select').at(-1).selection.node_id),'n1','cancel keeps the selected element')
  // Parent padding edge: start is 60px inside the content edge; within 2px snaps exactly.
  await target.click()
  await page.mouse.move(start.x,start.y);await page.mouse.down()
  await page.mouse.move(start.x-58,start.y+40,{steps:8})
  assert.ok(Math.abs((await target.boundingBox()).x-(initial.x-60))<1,'snaps to parent content edge')
  await page.keyboard.press('Escape');await page.mouse.up()
  await page.mouse.move(start.x,start.y);await page.mouse.down()
  await page.mouse.move(start.x+other.x+other.width-initial.x+5,start.y+other.y-initial.y+5,{steps:8})
  assert.ok(Math.abs((await target.boundingBox()).x-(other.x+other.width+5))<1,'five pixels away stays free instead of snapping')
  await page.mouse.move(start.x+other.x+other.width-initial.x+12,start.y+other.y-initial.y+12,{steps:4})
  assert.ok(Math.abs((await target.boundingBox()).x-(other.x+other.width+12))<1,'moving away releases alignment immediately')
  await page.keyboard.press('Escape');await page.mouse.up()
  await page.keyboard.down('Alt')
  await page.mouse.move(start.x,start.y);await page.mouse.down()
  await page.mouse.move(start.x+other.x+other.width-initial.x+2,start.y+other.y-initial.y+2,{steps:8})
  assert.ok(Math.abs((await target.boundingBox()).x-(other.x+other.width+2))<1,'Alt bypasses snapping')
  await page.keyboard.press('Escape');await page.mouse.up();await page.keyboard.up('Alt')
  await page.mouse.move(start.x,start.y);await page.mouse.down()
  await page.mouse.move(start.x+710,start.y+180,{steps:12});await page.mouse.up()
  await page.waitForFunction(()=>window.messages.filter(message=>message.type==='edit').length===2)
  assert.equal(await page.evaluate(()=>window.messages.filter(message=>message.type==='edit').at(-1).values.translate),'710px 180px','moving outside parent saves the new position without clamping')
  assert.equal(await target.evaluate(element=>element.parentElement.id),'stage','moving preserves source hierarchy')
  assert.ok((await target.boundingBox()).x>(await frame.locator('#stage').boundingBox()).x+(await frame.locator('#stage').boundingBox()).width,'element can leave parent bounds')
  await page.screenshot({path:'../../tmp/prototype-move/outside-parent.png'})
  await host({type:'preview-reset',node_id:'n1'})
  await target.evaluate(element=>{element.style.translate='20px 10px';element.style.transform='rotate(10deg)'})
  const shifted=await target.boundingBox()
  await page.keyboard.down('Alt')
  await page.mouse.move(shifted.x+shifted.width-12,shifted.y-16);await page.mouse.down()
  await page.mouse.move(shifted.x+shifted.width-12+30,shifted.y-16+40,{steps:8});await page.mouse.up();await page.keyboard.up('Alt')
  await page.waitForFunction(()=>window.messages.filter(message=>message.type==='edit').length===3)
  assert.equal(await page.evaluate(()=>window.messages.filter(message=>message.type==='edit').at(-1).values.translate),'50px 50px','existing translate is accumulated')
  assert.equal(await target.evaluate(element=>element.style.transform),'rotate(10deg)','existing transform is preserved')
  await page.keyboard.press('Control+z')
  await page.waitForFunction(()=>window.messages.some(message=>message.type==='undo-request'))
  assert.equal(await page.evaluate(()=>window.messages.filter(message=>message.type==='undo-request').length),1)
  await target.dblclick()
  await page.keyboard.press('Control+z')
  assert.equal(await page.evaluate(()=>window.messages.filter(message=>message.type==='undo-request').length),1,'inline text editing retains native undo')
  process.stdout.write('Prototype move: sibling/parent snapping, source operation, cancel and isolation passed.\n')
}finally{await browser.close()}
